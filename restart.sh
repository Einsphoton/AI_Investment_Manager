#!/bin/bash

# ============================================
# AI 投资分析平台 - 快捷重建重启脚本
# 执行：重新构建 Docker 镜像并重启容器
# ============================================

set -e

cd "$(dirname "$0")"

echo "============================================"
echo "  AI 投资分析平台 - 重建重启"
echo "============================================"
echo ""

# 1. 停止并删除旧容器
echo "[1/3] 停止旧容器..."
docker compose down
echo ""

# 2. 重新构建镜像（包含前后端最新代码）
echo "[2/3] 重新构建 Docker 镜像..."
docker compose build
echo ""

# 3. 启动新容器
echo "[3/3] 启动新容器..."
docker compose up -d
echo ""

echo "============================================"
echo "  ✅ 完成！访问地址: http://localhost:8000"
echo "============================================"
echo ""
echo "查看日志: docker compose logs -f"
